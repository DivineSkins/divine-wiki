import gamesIndex from "./draft/games-index.json";

/**
 * Games the wiki covers or is getting ready to cover, in the order the
 * homepage and the contribute picker list them. `slug` is the docs segment
 * (`content/docs/<locale>/<slug>/`) and matches the game's slug on
 * divineskins.gg. Covers are the games' Twitch box art (360x480 WebP), the
 * same files the divineskins.gg blog uses for its game cards.
 *
 * Client-safe: the guide counts that need the content source live in
 * src/lib/guide-count.ts.
 */
export const GAMES = [
  { slug: "lol", name: "League of Legends", cover: "/brand/games/lol.webp" },
  { slug: "deadlock", name: "Deadlock", cover: "/brand/games/deadlock.webp" },
] as const;

export type Game = (typeof GAMES)[number];

/** Where a new draft goes when nothing names a game. */
export const DEFAULT_GAME = "lol";

/**
 * Guide categories per game segment, in sidebar order. Generated by
 * scripts/prebuild.mjs from content/docs/en/<game>/.
 */
const CATEGORIES_BY_GAME: Record<string, string[]> = gamesIndex;

export function gameCategories(slug: string): string[] {
  return CATEGORIES_BY_GAME[slug] ?? [];
}

/**
 * True once the game's segment has category folders to put a new guide in.
 * Until then the contribute picker shows it as "Coming soon".
 */
export function acceptsGuides(slug: string): boolean {
  return gameCategories(slug).length > 0;
}

/** Labels for a game's status line, from `messages.home`. */
export interface GameStatusLabels {
  guideCount: string;
  guideCountOne: string;
  comingSoon: string;
}

/**
 * A game as the homepage and the header's Guides menu show it. `href` is
 * null until the game's segment has English guides; `status` is the guide
 * count or "Coming soon". Built on the server by `listGames()` in
 * src/lib/guide-count.ts, so client components get it as plain props.
 */
export interface GameEntry {
  slug: string;
  name: string;
  cover: string;
  href: string | null;
  status: string;
}
